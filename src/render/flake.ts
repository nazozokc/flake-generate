import type { ProjectInfo } from "../types.js";

const SYSTEMS = ["aarch64-darwin", "aarch64-linux", "x86_64-darwin", "x86_64-linux"];

export function renderFlake(info: ProjectInfo): string {
  const lines: string[] = [];

  lines.push("# Generated by flake-generate. Edit freely.");
  if (info.detections.length === 0) {
    lines.push("# Detected: no project markers");
  }
  for (const detection of info.detections) {
    const shown = detection.markers.slice(0, 6);
    const rest = detection.markers.length > shown.length ? ", ..." : "";
    lines.push(`# Detected: ${detection.label} (${shown.join(", ")}${rest})`);
  }

  lines.push(
    "",
    "{",
    `  description = ${JSON.stringify(`${info.name} development environment`)};`,
    "",
    "  inputs = {",
    '    nixpkgs.url = "github:NixOS/nixpkgs/nixos-unstable";',
    '    flake-parts.url = "github:hercules-ci/flake-parts";',
    "  };",
    "",
    "  outputs = inputs@{ self, nixpkgs, flake-parts, ... }:",
    "    flake-parts.lib.mkFlake { inherit inputs; } {",
    "      systems = [",
  );
  for (const system of SYSTEMS) {
    lines.push(`        ${JSON.stringify(system)}`);
  }
  lines.push(
    "      ];",
    "",
    "      perSystem = { system, ... }:",
    "        let",
    `          pkgs = nixpkgs.legacyPackages.\${system};`,
    "        in",
    "        {",
    "          devShells.default = pkgs.mkShell {",
    `            name = ${JSON.stringify(info.name)};`,
    "            packages = [",
  );

  if (info.detections.length === 0) {
    lines.push("              # No ecosystem detected; add packages here.");
  }
  for (const detection of info.detections) {
    lines.push(`              # ${detection.label}`);
    for (const packageName of detection.packages) {
      lines.push(`              pkgs.${packageName}`);
    }
  }

  lines.push(
    "            ];",
    "            shellHook = ''",
    '              echo "[devShell:default] ready"',
    "            '';",
    "          };",
    "        };",
    "    };",
    "}",
    "",
  );

  return lines.join("\n");
}
