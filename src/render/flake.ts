import {
  DEFAULT_NIXPKGS,
  DEFAULT_SYSTEMS,
  PACKAGES_BEGIN,
  PACKAGES_END,
  type ProjectInfo,
  type RenderOptions,
} from "../types.js";

function packageExpression(name: string): string {
  return name.startsWith("pkgs.") || name.includes(" or ") ? name : `pkgs.${name}`;
}

export function renderFlake(info: ProjectInfo, options: RenderOptions = {}): string {
  const lines: string[] = [];
  const systems = options.systems ?? DEFAULT_SYSTEMS;
  const nixpkgs = options.nixpkgs ?? DEFAULT_NIXPKGS;
  const description = options.description ?? `${info.name} development environment`;
  const extras = options.extraPackages ?? [];

  lines.push("# Generated by nix-flake-generate. Edit freely.");
  if (info.detections.length === 0) {
    lines.push("# Detected: no project markers");
  }
  for (const detection of info.detections) {
    const shown = detection.markers.slice(0, 6);
    const rest = detection.markers.length > shown.length ? ", ..." : "";
    lines.push(`# Detected: ${detection.label} (${shown.join(", ")}${rest})`);
  }

  lines.push(
    "",
    "{",
    `  description = ${JSON.stringify(description)};`,
    "",
    "  inputs = {",
    `    nixpkgs.url = ${JSON.stringify(nixpkgs)};`,
    '    flake-parts.url = "github:hercules-ci/flake-parts";',
    "  };",
    "",
    "  outputs = inputs@{ self, nixpkgs, flake-parts, ... }:",
    "    flake-parts.lib.mkFlake { inherit inputs; } {",
    "      systems = [",
  );
  for (const system of systems) {
    lines.push(`        ${JSON.stringify(system)}`);
  }
  lines.push(
    "      ];",
    "",
    "      perSystem = { system, ... }:",
    "        let",
    `          pkgs = nixpkgs.legacyPackages.\${system};`,
    "        in",
    "        {",
    "          devShells.default = pkgs.mkShell {",
    `            name = ${JSON.stringify(info.name)};`,
    "            packages = [",
    `              ${PACKAGES_BEGIN}`,
  );

  if (info.detections.length === 0 && extras.length === 0) {
    lines.push("              # No ecosystem detected; add packages here.");
  }
  for (const detection of info.detections) {
    lines.push(`              # ${detection.label}`);
    for (const packageName of detection.packages) {
      lines.push(`              ${packageExpression(packageName)}`);
    }
  }
  if (extras.length > 0) {
    lines.push("              # Additional");
    for (const packageName of extras) {
      lines.push(`              ${packageExpression(packageName)}`);
    }
  }
  lines.push(
    `              ${PACKAGES_END}`,
    "            ];",
    "            shellHook = ''",
    '              echo "[devShell:default] ready"',
    "            '';",
    "          };",
    "        };",
    "    };",
    "}",
    "",
  );

  return lines.join("\n");
}
